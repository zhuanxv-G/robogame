STARTUP_RAISE_PPS = 800


# ============================================================
# 打开 STM32 串口
# ============================================================

ser = serial.Serial(
    PORT,
    BAUD,
    timeout=0.1
)


# ============================================================
# 基础串口函数
# ============================================================

def tx(cmd):
    """向 STM32 发送一行命令。"""

    print(f"[TX] {cmd}")

    ser.write(
        (cmd + "\n").encode()
    )

    ser.flush()


def wait_for(expected_prefix, timeout=10.0):
    """
    等待 STM32 返回指定前缀。

    所有收到的数据都会打印。

    如果收到 ERR,...
    直接抛出异常。
    """

    deadline = time.time() + timeout

    while time.time() < deadline:

        line = (
            ser.readline()
            .decode(errors="ignore")
            .strip()
        )

        if not line:
            continue

        print(f"[RX] {line}")

        if line.startswith("ERR,"):
            raise RuntimeError(
                f"STM32 error: {line}"
            )

        if line.startswith(expected_prefix):
            return line

    raise TimeoutError(
        f"Timeout waiting for: {expected_prefix}"
    )


# ============================================================
# STM32 基础命令
# ============================================================

def hello():

    tx("HELLO_STM32,1")

    wait_for(
        "STM32_OK,1",
        2.0
    )


def stop():
    """
    发送全局 STOP。

    STOP 是 STM32 最高优先级安全命令。
    """

    tx("STOP")

    try:

        wait_for(
            "ACK,STOP",
            2.0
        )

    except Exception as e:

        print(
            f"[WARN] STOP response: {e}"
        )


# ============================================================
# Servo 控制
# ============================================================

def servo_get(index):

    tx(
        f"SERVO_GET,{index}"
    )

    line = wait_for(
        f"SERVO_POS,{index},",
        2.0
    )

    angle = int(
        line.split(",")[2]
    )

    return angle


def servo_set(index, angle, wait=0.0):
    """
    设置 Servo 绝对角度。

    SERVO_SET 没有 DONE。

    因此机械动作需要的等待时间
    由 Raspberry Pi 自己完成。
    """

    tx(
        f"SERVO_SET,{index},{angle}"
    )

    wait_for(
        f"ACK,SERVO_SET,{index},{angle}",
        2.0
    )

    if wait > 0:

        time.sleep(wait)


def servo_sweep(
    index,
    target,
    step_delay_ms
):
    """
    在 Raspberry Pi 侧模拟旧：

    Servo.Sweep_To(target, delay)

    每次变化 1°。
    """

    current = servo_get(index)

    if current == target:
        return

    direction = (
        1
        if target > current
        else -1
    )

    for angle in range(
        current + direction,
        target + direction,
        direction
    ):

        servo_set(
            index,
            angle
        )

        time.sleep(
            step_delay_ms / 1000.0
        )


# ============================================================
# Stepper 控制
# ============================================================

def stepper_move(
    steps,
    pps=800
):
    """
    正式 Stepper 控制。

    正数 = 下降
    负数 = 上升

    必须：

    ACK
        ↓
    等待 MOVE_DONE
        ↓
    才返回
    """

    tx(
        f"STEPPER_MOVE,{steps},{pps}"
    )

    wait_for(
        f"ACK,STEPPER_MOVE,{steps},{pps}",
        2.0
    )

    # 理论运动时间
    nominal = (
        abs(steps) / float(pps)
    )

    # 给加减速和串口留足裕量
    timeout = (
        nominal * 2.0 + 8.0
    )

    wait_for(
        f"STEPPER_MOVE_DONE,{steps}",
        timeout
    )


# ============================================================
# 程序启动时自动上升
# ============================================================

def startup_raise():
    """
    每次执行 build_sequence.py 时：

    HELLO成功
        ↓
    Stepper固定向上移动1500步
        ↓
    等待DONE
        ↓
    才进入搭建程序

    注意：

    目前没有上限位器。

    所以这不是严格意义上的机械回零。
    """

    print()
    print(
        "========================================"
    )
    print(
        "        STARTUP STEPPER RAISE"
    )
    print(
        "========================================"
    )

    print(
        f"Raise: "
        f"{STARTUP_RAISE_STEPS} steps "
        f"@ {STARTUP_RAISE_PPS} pps"
    )

    stepper_move(
        STARTUP_RAISE_STEPS,
        STARTUP_RAISE_PPS
    )

    print(
        "Startup raise completed."
    )

    print(
        "========================================"
    )
    print()


