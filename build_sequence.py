def main():

    print()
    print(
        "========================================"
    )
    print(
        "       RoboGame Build Sequence"
    )
    print(
        "========================================"
    )

    print(
        f"STM32: {PORT} @ {BAUD}"
    )

    print()


    # 给串口一点初始化时间

    time.sleep(0.5)


    # --------------------------------------------------------
    # STM32握手
    # --------------------------------------------------------

    print(
        "Connecting STM32..."
    )

    hello()

    print(
        "STM32 connected."
    )


    # --------------------------------------------------------
    # 每次启动先固定向上移动
    # --------------------------------------------------------

    startup_raise()


    # --------------------------------------------------------
    # 菜单
    # --------------------------------------------------------

    print(
        "1 = run group 1"
    )

    print(
        "2 = run group 2"
    )

    print(
        "3 = run group 3"
    )

    print(
        "a = run ALL groups"
    )

    print(
        "s = STOP"
    )

    print(
        "q = quit"
    )


    while True:

        choice = (
            input(
                "\nSELECT > "
            )
            .strip()
            .lower()
        )


        # ----------------------------------------------------
        # Group 1
        # ----------------------------------------------------

        if choice == "1":

            group1()


        # ----------------------------------------------------
        # Group 2
        # ----------------------------------------------------

        elif choice == "2":

            group2()


        # ----------------------------------------------------
        # Group 3
        # ----------------------------------------------------

        elif choice == "3":

            group3()


        # ----------------------------------------------------
        # 全流程
        # ----------------------------------------------------

        elif choice == "a":

            confirm = (
                input(
                    "Run ALL build actions? "
                    "(yes/no) > "
                )
                .strip()
                .lower()
            )

            if confirm == "yes":

                run_all()

            else:

                print(
                    "Cancelled."
                )


        # ----------------------------------------------------
        # STOP
        # ----------------------------------------------------

        elif choice == "s":

            stop()


        # ----------------------------------------------------
        # 退出
        # ----------------------------------------------------

        elif choice == "q":

            stop()

            break


        else:

            print(
                "Unknown selection."
            )


